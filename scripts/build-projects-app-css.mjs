// Builds app/components/pro-projects-app.css, the /pro demo's copy of the
// LLMnesia Projects app stylesheet. Every class gets a pj- prefix, every rule
// is scoped under .pjx, keyframes are renamed, and only rules for classes the
// demo components use are kept.
//
// Usage: node scripts/build-projects-app-css.mjs <path to the app's styles.css>

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2];
if (!source) throw new Error('Pass the path to the Projects app styles.css');

// Classes the demo uses. A class built from a template, such as pill-${status},
// keeps every class starting with its fixed part.
const used = new Set(['current']);
const families = new Set();
for (const file of ['pro-board-demo.js', 'pro-demo-board.js', 'pro-demo-card.js', 'pro-demo-ui.js']) {
  const code = readFileSync(join(root, 'app/components', file), 'utf8');
  for (const match of code.matchAll(/\bc\((?:'([^']*)'|`([^`]*)`)\)/g)) {
    const body = (match[1] ?? match[2]).replace(/\$\{[^}]*\}/g, '\u0000');
    for (const token of body.split(/\s+/)) {
      if (!token) continue;
      if (!token.includes('\u0000')) used.add(token);
      else if (token.split('\u0000')[0]) families.add(token.split('\u0000')[0]);
    }
  }
}

const classOf = /\.(-?[_a-zA-Z][\w-]*)/g;
const keep = (selector) => [...selector.matchAll(classOf)].every(([, name]) =>
  used.has(name) || [...families].some((prefix) => name.startsWith(prefix)));

const scope = (selector) => {
  const prefixed = selector.replace(classOf, '.pj-$1');
  if (/^(:root|html|body)\b/.test(prefixed)) return prefixed.replace(/^(:root|html|body)/, '.pjx');
  return `.pjx ${prefixed}`;
};

const css = postcss.parse(readFileSync(source, 'utf8'));
const keyframes = new Set();
css.walkAtRules('keyframes', (rule) => {
  keyframes.add(rule.params);
  rule.params = `pj-${rule.params}`;
});
css.walkAtRules('font-face', (rule) => {
  rule.walkDecls('src', (decl) => {
    decl.value = decl.value.replace(/url\("fonts\//g, 'url("/fonts/plex/');
  });
});
css.walkRules((rule) => {
  if (rule.parent.type === 'atrule' && rule.parent.name === 'keyframes') return;
  const selectors = rule.selectors.filter(keep);
  if (!selectors.length) {
    rule.remove();
    return;
  }
  rule.selectors = selectors.map(scope);
});
css.walkDecls(/^animation(-name)?$/, (decl) => {
  for (const name of keyframes) decl.value = decl.value.replace(new RegExp(`\\b${name}\\b`, 'g'), `pj-${name}`);
});
css.walkAtRules('media', (rule) => {
  if (!rule.nodes.length) rule.remove();
});

const header = '/* Generated by scripts/build-projects-app-css.mjs from the LLMnesia Projects app stylesheet. Do not edit by hand. */\n';
writeFileSync(join(root, 'app/components/pro-projects-app.css'), header + css.toString());
console.log(`${used.size} classes and ${families.size} class families kept`);
